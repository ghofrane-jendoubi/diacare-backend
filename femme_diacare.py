def build_features(data: dict) -> pd.DataFrame:
    """Reconstruit les 13 features à partir des 8 variables brutes."""
    preg = float(data["Pregnancies"])
    gluc = float(data["Glucose"])
    bp   = float(data["BloodPressure"])
    skin = float(data["SkinThickness"])
    ins  = float(data["Insulin"])
    bmi  = float(data["BMI"])
    dpf  = float(data["DiabetesPedigreeFunction"])
    age  = float(data["Age"])

    row = {
        "Pregnancies"            : preg,
        "Glucose"                : gluc,
        "BloodPressure"          : bp,
        "SkinThickness"          : skin,
        "Insulin"                : ins,
        "BMI"                    : bmi,
        "DiabetesPedigreeFunction": dpf,
        "Age"                    : age,
        # Feature engineering — identique au notebook
        "BMI_Age"                : bmi * age,
        "Glucose_sq"             : gluc ** 2,
        "Insulin_Glucose"        : ins / (gluc + 1),
        "Age_cat"                : 0 if age < 30 else (1 if age <= 45 else 2),
        "Risk_score"             : (gluc/GLUCOSE_MAX + bmi/BMI_MAX + age/AGE_MAX) / 3,
    }
    return pd.DataFrame([row])[FEATURE_NAMES]


def validate_input(data: dict) -> list:
    """Valide les 8 champs requis et leurs plages médicales."""
    errors = []
    fields = {
        "Pregnancies"            : (0,   20,   "Grossesses"),
        "Glucose"                : (44,  200,  "Glucose (mg/dL)"),
        "BloodPressure"          : (24,  122,  "Pression artérielle (mm Hg)"),
        "SkinThickness"          : (0,   110,  "Épaisseur cutanée (mm)"),
        "Insulin"                : (0,   850,  "Insuline (µU/mL)"),
        "BMI"                    : (10,  70,   "IMC"),
        "DiabetesPedigreeFunction": (0.0, 2.5, "Indice familial"),
        "Age"                    : (18,  90,   "Âge"),
    }
    for field, (lo, hi, label) in fields.items():
        if field not in data:
            errors.append(f"Champ manquant : {field}")
            continue
        try:
            val = float(data[field])
            if not (lo <= val <= hi):
                errors.append(f"{label} hors plage : {val} (attendu {lo}–{hi})")
        except (ValueError, TypeError):
            errors.append(f"{field} doit être un nombre")
    return errors


def interpret_result(proba: float, pred: int) -> dict:
    pct = round(proba * 100, 1)
    if pred == 0:
        level, color = ("très faible", "green") if proba < 0.20 else ("modéré", "yellow")
        msg = "Les paramètres n'indiquent pas de risque de diabète." if proba < 0.20 \
              else "Paramètres dans la normale — surveillance conseillée."
    else:
        level, color = ("modéré-élevé", "orange") if proba < 0.65 else ("élevé", "red")
        msg = "Certains indicateurs suggèrent un risque. Consultez un médecin." if proba < 0.65 \
              else "Indicateurs fortement associés au diabète. Consultation recommandée."

    return {
        "prediction"      : int(pred),
        "label"           : "Diabétique" if pred == 1 else "Non-diabétique",
        "probability"     : round(proba, 4),
        "probability_pct" : pct,
        "risk_level"      : level,
        "color"           : color,
        "message"         : msg,
        "threshold_used"  : THRESHOLD,
        "disclaimer"      : "Résultat indicatif. Ne remplace pas un avis médical.",
    }


def require_json(f):
    @wraps(f)
    def wrapper(*args, **kwargs):
        if not request.is_json:
            return jsonify({"error": "Content-Type doit être application/json"}), 415
        return f(*args, **kwargs)
    return wrapper

