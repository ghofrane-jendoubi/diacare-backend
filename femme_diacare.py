@app.route("/api/predict", methods=["POST"])
@require_json
def predict():
    """
    Prédiction pour un seul patient.

    Exemple de corps JSON :
    {
        "Pregnancies": 3, "Glucose": 120, "BloodPressure": 70,
        "SkinThickness": 25, "Insulin": 80, "BMI": 28.5,
        "DiabetesPedigreeFunction": 0.45, "Age": 35
    }
    """
    data   = request.get_json()
    errors = validate_input(data)
    if errors:
        return jsonify({"success": False, "errors": errors}), 400

    try:
        X_df    = build_features(data)
        X_sc    = SCALER.transform(X_df)
        proba   = MODEL.predict_proba(X_sc)[0][1]
        pred    = int(proba >= THRESHOLD)
        result  = interpret_result(proba, pred)

        logger.info(f"Predict → {result['label']} ({proba:.3f}) | {request.remote_addr}")

        return jsonify({
            "success"      : True,
            "result"       : result,
            "features_used": X_df.iloc[0].round(4).to_dict(),
            "timestamp"    : datetime.utcnow().isoformat() + "Z",
        })

    except Exception as e:
        logger.exception("Erreur prédiction")
        return jsonify({"success": False, "error": "Erreur interne"}), 500


@app.route("/api/predict/batch", methods=["POST"])
@require_json
def predict_batch():
    """Prédiction pour plusieurs patients (max 50)."""
    data = request.get_json()
    if "patients" not in data or not isinstance(data["patients"], list):
        return jsonify({"success": False, "error": "Clé 'patients' requise (liste)"}), 400
    if len(data["patients"]) > 50:
        return jsonify({"success": False, "error": "Maximum 50 patients par requête"}), 400

    results = []
    for i, patient in enumerate(data["patients"]):
        errors = validate_input(patient)
        if errors:
            results.append({"index": i, "success": False, "errors": errors})
            continue
        try:
            X_df  = build_features(patient)
            X_sc  = SCALER.transform(X_df)
            proba = MODEL.predict_proba(X_sc)[0][1]
            pred  = int(proba >= THRESHOLD)
            results.append({"index": i, "success": True, "result": interpret_result(proba, pred)})
        except Exception as e:
            results.append({"index": i, "success": False, "error": str(e)})

    ok = sum(1 for r in results if r.get("success"))
    return jsonify({
        "success"      : True,
        "total"        : len(data["patients"]),
        "success_count": ok,
        "results"      : results,
        "timestamp"    : datetime.utcnow().isoformat() + "Z",
    })


