def load_model():
    try:
        model  = joblib.load(MODEL_PATH)
        scaler = joblib.load(SCALER_PATH)
        with open(META_PATH, "r", encoding="utf-8") as f:
            metadata = json.load(f)
        logger.info(f"✓ Modèle chargé — AUC: {metadata['metrics']['roc_auc']}")
        return model, scaler, metadata
    except FileNotFoundError as e:
        logger.error(f"✗ Fichier introuvable : {e}")
        logger.error(f"  Vérifie que tes .pkl sont dans : {MODELS_DIR}")
        raise

MODEL, SCALER, METADATA = load_model()
THRESHOLD     = METADATA.get("threshold", 0.40)
FEATURE_NAMES = METADATA.get("features", [])

# Valeurs max du dataset Pima — nécessaires pour Risk_score
GLUCOSE_MAX = 199.0
BMI_MAX     = 67.1
AGE_MAX     = 81.0

